-- A list of nurseries' own sales sites. Read: published rows only (admins see all). Write: admins only.
-- Rows start unpublished; the page shows 「近日公開」 to everyone until the owner opens it.
create table if not exists public.nurseries (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  url text not null unique check (url ~ '^https://'),
  country text not null default '日本',
  instagram text check (instagram is null or instagram ~ '^https://'),
  note text check (note is null or length(note) <= 200),
  is_published boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.nurseries enable row level security;

drop policy if exists "Read published nurseries" on public.nurseries;
create policy "Read published nurseries" on public.nurseries
  for select using (is_published or public.is_admin());

drop policy if exists "Admins write nurseries" on public.nurseries;
create policy "Admins write nurseries" on public.nurseries
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.nurseries to anon, authenticated;
grant insert, update, delete on public.nurseries to authenticated;

select count(*) as nurseries from public.nurseries;
